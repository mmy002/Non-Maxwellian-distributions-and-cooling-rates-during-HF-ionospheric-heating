function [E_old,xs_old] = p_data_N2_el()

% Convert from cm to m
cm_to_m = 0.01; 

% Convert from [eV] to [J] 
eVtoJ = 1.602176634e-19;    

%----------------------------------------------------------------------------------------------------------------
% OUTSIDE OF RESONANCE REGION 
%----------------------------------------------------------------------------------------------------------------
% Figure 4.1 in Itikawa 1986. Units: cm^2 per energy eV
N2_el = load('N2_el.mat'); 
E_old_other = (10.^(N2_el.N2_el(:,1)))*eVtoJ;
xs_old_other = (10.^N2_el.N2_el(:,2))*(cm_to_m)^2; 
E_old_other(12:14) = []; 
xs_old_other(12:14) = []; 

%----------------------------------------------------------------------------------------------------------------
% RESONANCE REGION 
%----------------------------------------------------------------------------------------------------------------
% Figure 4.2 in Itikawa 1986. Units: 10^-16 cm^2 per energy eV
N2_el_res = load('N2_el_res.mat'); 
E_old_res = (N2_el_res.N2_el_res(:,1))*eVtoJ;
xs_old_res = (N2_el_res.N2_el_res(:,2))*1e-16*(cm_to_m)^2; 

%----------------------------------------------------------------------------------------------------------------
% COMBINE TO ONE DATA SET
%----------------------------------------------------------------------------------------------------------------
E_old = [E_old_other(1:11); E_old_res; E_old_other(12:end)];  
xs_old = [xs_old_other(1:11); xs_old_res; xs_old_other(12:end)];  